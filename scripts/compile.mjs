// Compiles contracts/*.sol with solc and writes:
//   artifacts/<Name>.json   full output (abi + bytecode) for the deploy script
//   shared/abi.ts           typed `as const` ABIs the app and server import
//
// solc is loaded lazily because it is a large module and only this script needs it.

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contractsDir = join(root, "contracts");
const artifactsDir = join(root, "artifacts");

const sources = {};
for (const file of readdirSync(contractsDir).filter((f) => f.endsWith(".sol"))) {
  sources[file] = { content: readFileSync(join(contractsDir, file), "utf8") };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  },
};

const solc = (await import("solc")).default;
const output = JSON.parse(solc.compile(JSON.stringify(input)));

const errors = (output.errors ?? []).filter((e) => e.severity === "error");
const warnings = (output.errors ?? []).filter((e) => e.severity === "warning");

for (const w of warnings) console.warn(`warning: ${w.formattedMessage.trim()}`);

if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

mkdirSync(artifactsDir, { recursive: true });

const wanted = ["RemiPayouts", "DemoUSD"];
const abis = {};

for (const [file, contracts] of Object.entries(output.contracts ?? {})) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!wanted.includes(name)) continue;
    const bytecode = `0x${c.evm.bytecode.object}`;
    writeFileSync(
      join(artifactsDir, `${name}.json`),
      `${JSON.stringify({ contractName: name, sourceFile: file, abi: c.abi, bytecode }, null, 2)}\n`,
    );
    abis[name] = c.abi;
    const kb = (bytecode.length / 2 / 1024).toFixed(1);
    console.log(`${name.padEnd(13)} ${kb} KB  ${c.abi.length} abi entries`);
  }
}

const missing = wanted.filter((n) => !(n in abis));
if (missing.length > 0) {
  console.error(`compiled output is missing: ${missing.join(", ")}`);
  process.exit(1);
}

const header = `// Generated by scripts/compile.mjs. Do not edit.
// Run \`npm run compile\` after changing anything in contracts/.
`;

const body = Object.entries(abis)
  .map(([name, abi]) => `export const ${name.charAt(0).toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;`)
  .join("\n\n");

// Written into each workspace rather than a shared folder: one file outside both
// tsconfig rootDirs costs more config than one generated copy per workspace.
const targets = [join(root, "server", "src", "generated"), join(root, "app", "src", "generated")];
for (const dir of targets) {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "abi.ts"), `${header}\n${body}\n`);
}
console.log(`wrote artifacts/ and abi.ts into ${targets.length} workspaces`);
